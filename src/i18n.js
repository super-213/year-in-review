export function translate(language, key, params = {}) {
  const text = MESSAGES[key]?.[language] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => params[name] ?? match);
}

// Translate only untouched defaults, preserving all user edits and page identities.
export function translateDefaults(value, source, target) {
  if (typeof value === 'string') return value === source && typeof target === 'string' ? target : value;
  if (Array.isArray(value)) return value.map((item, index) => {
    const sourceIndex = item?.id === undefined ? index : source?.findIndex(entry => entry.id === item.id);
    return translateDefaults(item, source?.[sourceIndex], target?.[sourceIndex]);
  });
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, translateDefaults(item, source?.[key], target?.[key])]));
  return value;
}
